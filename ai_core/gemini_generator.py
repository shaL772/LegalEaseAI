from __future__ import annotations

from textwrap import dedent

from config import settings

try:
    from google import genai
except ImportError:
    genai = None


SYSTEM_INSTRUCTION = dedent(
    """
    You are LegalEase, an AI drafting assistant for
    generating structured legal-document drafts.

    Your task is to generate a professional legal-document draft
    using only the facts supplied by the user.

    IMPORTANT RULES:

    1. Do not invent names.
    2. Do not invent dates.
    3. Do not invent addresses.
    4. Do not invent payment amounts.
    5. Do not invent governing laws.
    6. Do not invent obligations not supplied by the user.
    7. If an important detail is missing, use a placeholder such as:
       [INSERT ADDRESS]
       [INSERT AMOUNT]
       [INSERT JURISDICTION]

    The generated document should be:

    - professional
    - structured
    - readable
    - editable
    - clearly divided into sections
    - suitable as a draft

    Recommended structure:

    TITLE

    PARTIES / PREAMBLE

    BACKGROUND / RECITALS where appropriate

    NUMBERED SECTIONS

    TERMS AND CONDITIONS

    SIGNATURE SECTION

    DISCLAIMER

    Do not claim that the document is automatically legally valid.

    Do not provide legal advice.

    Return plain text only.

    Do not wrap the answer inside markdown code fences.
    """
).strip()


class GeminiDocumentGenerator:
    """
    Generates legal-document drafts through Gemini.

    MOCK_MODE=true:
        Uses local document generation and does not contact Gemini.

    MOCK_MODE=false:
        Uses the Google Gemini API.
    """

    def __init__(self) -> None:
        self.model = settings.gemini_model

        self._client = None

        if not settings.mock_mode:

            if genai is None:
                raise RuntimeError(
                    "The google-genai package is not installed. "
                    "Run: pip install -r requirements.txt"
                )

            if not settings.gemini_api_key:
                raise RuntimeError(
                    "GEMINI_API_KEY is not configured. "
                    "Add it to your .env file or use MOCK_MODE=true."
                )

            self._client = genai.Client(
                api_key=settings.gemini_api_key
            )

    @staticmethod
    def _build_prompt(
        document_type: str,
        parties: str,
        terms: str,
        effective_date: str,
    ) -> str:

        return dedent(
            f"""
            Create a draft legal document.

            DOCUMENT TYPE:
            {document_type}

            EFFECTIVE DATE:
            {effective_date}

            PARTIES:
            {parties}

            USER-PROVIDED TERMS:
            {terms}

            REQUIREMENTS:

            1. Preserve all user-provided facts.
            2. Organize the terms into clear sections.
            3. Convert semicolon-separated terms into numbered clauses.
            4. Use professional legal-document wording.
            5. Do not add unsupported facts.
            6. Use placeholders for missing information.
            7. Include signature blocks.
            8. Keep the result editable.
            9. End with this disclaimer:

            Draft generated by LegalEase.
            Review with a qualified legal professional before signing.

            Return only the document text.
            """
        ).strip()

    def _mock_document(
        self,
        document_type: str,
        parties: str,
        terms: str,
        effective_date: str,
    ) -> str:

        term_items = [
            item.strip()
            for item in terms.split(";")
            if item.strip()
        ]

        lines = [
            document_type.upper(),
            "",
            f"Effective Date: {effective_date}",
            "",
            "PARTIES",
            parties,
            "",
            "TERMS AND CONDITIONS",
        ]

        for index, item in enumerate(
            term_items,
            start=1,
        ):
            lines.append(
                f"{index}. {item}"
            )

        lines.extend(
            [
                "",
                "SIGNATURES",
                "",
                "Party / Authorized Representative:",
                "________________________________",
                "",
                "Signature:",
                "________________________________",
                "",
                "Date:",
                "________________________________",
                "",
                "Draft generated by LegalEase. "
                "Review with a qualified legal professional before signing.",
            ]
        )

        return "\n".join(lines)

    def generate_document(
        self,
        document_type: str,
        parties: str,
        terms: str,
        effective_date: str,
    ) -> str:

        if settings.mock_mode:
            return self._mock_document(
                document_type=document_type,
                parties=parties,
                terms=terms,
                effective_date=effective_date,
            )

        prompt = self._build_prompt(
            document_type=document_type,
            parties=parties,
            terms=terms,
            effective_date=effective_date,
        )

        response = self._client.models.generate_content(
            model=self.model,
            contents=prompt,
            config={
                "system_instruction": SYSTEM_INSTRUCTION,
                "temperature": 0.2,
            },
        )

        text = getattr(
            response,
            "text",
            None,
        )

        if not text or not text.strip():
            raise RuntimeError(
                "Gemini returned an empty document."
            )

        return text.strip()